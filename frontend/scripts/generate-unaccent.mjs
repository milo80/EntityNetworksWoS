// Generates src/lib/unaccent.generated.ts from PostgreSQL's unaccent.rules, so the
// Records highlight folds text exactly as the server's lower(unaccent(...)) does.
// From frontend/, with the dev database container from the README running:
//
//   podman exec entitynet-db sh -c 'cat "$(pg_config --sharedir)/tsearch_data/unaccent.rules"' \
//     | node scripts/generate-unaccent.mjs
//
// Regenerate when the PostgreSQL image changes (backend/tests/api/test_api_profile.py
// checks the table against the database's unaccent).
import { readFileSync, writeFileSync } from "node:fs";
import console from "node:console";
import process from "node:process";
import { URL } from "node:url";
import { format } from "prettier";

const OUT = new URL("../src/lib/unaccent.generated.ts", import.meta.url);

/** As contrib/unaccent: source, whitespace, target; a target may be "quoted"; none = remove. */
function parse(rules) {
  const table = {};
  for (const line of rules.split("\n")) {
    const m = /^(\S+)(?:\s+(.*?))?\s*$/u.exec(line);
    if (!m) continue;
    let target = m[2] ?? "";
    if (target.length >= 2 && target.startsWith('"') && target.endsWith('"')) {
      target = target.slice(1, -1).replace(/""/g, '"');
    }
    table[m[1]] = target;
  }
  return table;
}

const table = parse(readFileSync(process.stdin.fd, "utf8"));
const count = Object.keys(table).length;
if (count < 1000) throw new Error(`Only ${count} rules read: is unaccent.rules on stdin?`);

const source = `// GENERATED by scripts/generate-unaccent.mjs from PostgreSQL 16's unaccent.rules. Do not edit.
// Regenerate (from frontend/, dev database container running):
//   podman exec entitynet-db sh -c 'cat "$(pg_config --sharedir)/tsearch_data/unaccent.rules"' \\
//     | node scripts/generate-unaccent.mjs

/** Character -> what PostgreSQL's unaccent replaces it with ("" = removed). ${count} rules. */
export const UNACCENT: Readonly<Record<string, string>> = ${JSON.stringify(table)};
`;
writeFileSync(OUT, await format(source, { parser: "typescript", filepath: OUT.pathname }));
console.log(`Wrote ${count} rules to ${OUT.pathname}`);
